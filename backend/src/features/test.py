def build_prompt(
    audience_description: str,
    learning_objectives: list[str],
    order: int,
    lesson_description: str,
) -> str:
    objectives_text = ", ".join(learning_objectives)
    return (
        "Спланируй структуру урока на основе следующих данных:\n"
        f"        **Целевая аудитория:** {audience_description}\n"
        f"        **Цели обучения курса:** {objectives_text}\n"
        f"        **Порядковый номер урока в модуле:** {order}\n"
        f"        **Описание урока:** {lesson_description}\n"
        "        Требования к результату:\n"
        "        1. Сформируй 4–5 контент-блоков, покрывающих тему урока от введения до закрепления.\n"
        "        2. Для каждого блока напиши подробный промпт (минимум 4–5 предложений),\n"
        "           учитывающий уровень аудитории и цели урока.\n"
        "        3. Выбери тип каждого блока исходя из содержания (text, program_code, mermaid,\n"
        "           quiz, math_formula, chemical_formula, musical_notation, image)\n"
        "        "
    )


